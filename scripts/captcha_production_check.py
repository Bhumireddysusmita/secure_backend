"""Brief section 05: demonstrate production server-side CAPTCHA validation, repeatably.

  python scripts/captcha_production_check.py

Uses the REAL Turnstile secret from backend/.env (refuses to run with Cloudflare's test keys)
and shows that tokens which did not come from a real, solved widget are rejected:
  1. directly at Cloudflare's siteverify endpoint (raw response and error codes), and
  2. through the app's own API (POST /api/auth/signup and /api/auth/login), in-process,
     against the *_test database, using the real verifier (no mocks).
Writes reports/captcha-production-check.md. The secret key is never printed or written.

The "a real human passes" half cannot be automated by design (Turnstile refuses automated
browsers); it is recorded in docs/security.md.
"""

import os
import sys
from datetime import datetime, timezone
from pathlib import Path

import httpx
from dotenv import dotenv_values

BACKEND = Path(__file__).resolve().parent.parent
ROOT = BACKEND.parent
env = dotenv_values(BACKEND / ".env")

secret = os.environ.get("TURNSTILE_SECRET_KEY") or env.get("TURNSTILE_SECRET_KEY") or ""
if not secret or secret[:2] in {"1x", "2x", "3x"}:
    sys.exit("TURNSTILE_SECRET_KEY in backend/.env is missing or a Cloudflare TEST key. Put the real secret there to run this check.")
test_db = os.environ.get("TEST_DATABASE_URL") or env.get("TEST_DATABASE_URL") or ""
if not test_db.rsplit("/", 1)[-1].split("?")[0].endswith("_test"):
    sys.exit("TEST_DATABASE_URL must point at a *_test database.")

# The in-process API must use the real secret and the test database.
os.environ.update({"TURNSTILE_SECRET_KEY": secret, "DATABASE_URL": test_db, "APP_ENV": "test"})
sys.path.insert(0, str(BACKEND))

from fastapi.testclient import TestClient  # noqa: E402

from app.config import get_settings  # noqa: E402
from app.main import app  # noqa: E402

VERIFY_URL = get_settings().turnstile_verify_url
TOKENS = [
    ("forged random token", "forged-token-1234567890"),
    ("Cloudflare TEST token (from test site keys)", "XXXX.DUMMY.TOKEN.XXXX"),
    ("expired/garbage token shape", "0." + "A" * 300),
]

rows_direct = []
with httpx.Client(timeout=10) as http:
    for label, token in TOKENS:
        r = http.post(VERIFY_URL, data={"secret": secret, "response": token})
        body = r.json()
        rows_direct.append((label, r.status_code, body.get("success"), ", ".join(body.get("error-codes", [])) or "-"))

rows_api = []
stamp = int(datetime.now().timestamp())
with TestClient(app) as client:
    for label, token in TOKENS + [("no token at all", None)]:
        signup = {
            "name": "Prod Check",
            "email": f"prod.check.{stamp}.{len(rows_api)}@example.com",
            "password": "Lantern42zq",
            "confirmPassword": "Lantern42zq",
            "acceptTerms": True,
        }
        login = {"email": signup["email"], "password": signup["password"]}
        if token is not None:
            signup["captchaToken"] = token
            login["captchaToken"] = token
        s = client.post("/api/auth/signup", json=signup)
        l = client.post("/api/auth/login", json=login)
        rows_api.append((label, s.status_code, s.json().get("error", {}).get("code", "-"), l.status_code, l.json().get("error", {}).get("code", "-")))

direct_ok = all(r[2] is False for r in rows_direct)
api_ok = all(r[1] == 403 and r[3] == 403 for r in rows_api)
passed = direct_ok and api_ok

now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
out = [
    "# Production CAPTCHA verification check",
    "",
    "Machine-generated by `backend/scripts/captcha_production_check.py`. Uses the **real** Cloudflare Turnstile secret key "
    f"(prefix `{secret[:4]}…`, not a test key; the key itself is never written). Run: {now}.",
    "",
    f"**Result: {'PASS' if passed else 'FAIL'}.** Every token that did not come from a real, solved Turnstile widget was rejected.",
    "",
    "## 1. Cloudflare siteverify, called directly with the real secret",
    "",
    "| Token | HTTP | success | error-codes |",
    "|---|---|---|---|",
    *[f"| {a} | {b} | {str(c).lower()} | {d} |" for a, b, c, d in rows_direct],
    "",
    "## 2. The app's API, using its real server-side verifier (no mocks)",
    "",
    "| Token | Sign-up status | Sign-up error | Login status | Login error |",
    "|---|---|---|---|---|",
    *[f"| {a} | {b} | `{c}` | {d} | `{e}` |" for a, b, c, d, e in rows_api],
    "",
    "Expected: `403 captcha_failed` for every row. The API fails closed: missing token, invalid token, "
    "Cloudflare rejection, timeout or network error all mean \"not verified\".",
    "",
    "## The human side",
    "",
    "A real person solving the real widget is accepted; Turnstile refuses automated browsers, so this half "
    "cannot be scripted. Recorded on 2026-11-05 in [docs/security.md](../docs/security.md#captcha-production-verification): "
    "an automated Playwright browser was challenged and never received a token, while a human browser passed.",
    "",
    "Reproduce: put the real Turnstile secret in `backend/.env`, then `cd backend && .venv/Scripts/python scripts/captcha_production_check.py`.",
    "",
]
(ROOT / "reports").mkdir(exist_ok=True)
(ROOT / "reports" / "captcha-production-check.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
print(f"{'PASS' if passed else 'FAIL'}: direct siteverify rejections {sum(r[2] is False for r in rows_direct)}/{len(rows_direct)}, "
      f"API 403s {sum(r[1] == 403 and r[3] == 403 for r in rows_api)}/{len(rows_api)}")
print("Report: reports/captcha-production-check.md")
sys.exit(0 if passed else 1)
